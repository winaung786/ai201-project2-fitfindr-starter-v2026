"""Run a real Flask/MCP fallback-mode smoke session for Unit 9.

This verifies the local-with-logs operational path without an API key.
It is NOT the student's five acceptance criteria or the before/after test.
"""
from __future__ import annotations

import json
import os
import sys
from pathlib import Path
from statistics import mean

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))  # python scripts/foo.py otherwise cannot import root serve.py
LOG = ROOT / "results" / "capstone-smoke.jsonl"
os.environ["FITFINDR_LOG_PATH"] = str(LOG)
os.environ["AI201_CACHE"] = "0"
# No test credentials. Record that this is the model-unavailable fallback mode.
os.environ.pop("GEMINI_API_KEY", None)
os.environ.pop("FITFINDR_MCP_MODEL_LOG", None)

from serve import app  # noqa: E402


QUERIES = [
    "vintage graphic tee under $30, size M",
    "vintage graphic tee under $30, size XL",
    "designer ballgown size XXS under $5",
    "denim jacket under $50",
    "90s track jacket under $45, size M",
    "platform sneakers size 8",
    "silk slip dress under $40",
    "vintage graphic tee under $30",
    "designer ballgown size XXS under $5",
    "vintage graphic tee under $30, size M",
]


def main():
    LOG.parent.mkdir(parents=True, exist_ok=True)
    LOG.unlink(missing_ok=True)
    with app.test_client() as client:
        for i, query in enumerate(QUERIES, start=1):
            result = client.post("/ask", json={"query": query})
            assert result.status_code == 200, (i, result.status_code, result.get_json())
            assert result.headers.get("X-FitFindr-Run-ID"), i
        bad = client.post("/ask", json={})
        assert bad.status_code == 400, bad.get_json()

    records = [json.loads(line) for line in LOG.read_text(encoding="utf-8").splitlines()]
    assert len(records) == 11, len(records)
    assert all(r["timestamp"] and r["run_id"] and r["duration_ms"] >= 0 for r in records)
    assert all("input" in r and "output" in r and "model_tokens" in r for r in records)
    assert records[-1]["http_status"] == 400
    assert any(r["output"].get("retry_notice") for r in records[:10])
    assert any(r["output"].get("fit_card") for r in records[:10])
    assert any(r["output"].get("error") for r in records[:10])

    elapsed = [r["duration_ms"] for r in records[:10]]
    summary = {
        "mode": "real Flask test_client + actual MCP subprocess; no API key, local fallbacks",
        "not_a_live_model_evaluation": True,
        "http_requests": len(records),
        "valid_requests": 10,
        "rejected_requests": 1,
        "mean_duration_seconds_per_valid_request": round(mean(elapsed) / 1000, 4),
        "seconds_for_100_runs_at_observed_average": round(mean(elapsed) * 100 / 1000, 2),
        "total_model_calls_observed": sum(r["model_calls"] for r in records),
        "tokens_observed": sum(r["model_tokens"]["total"] for r in records),
        "measurement_method": "time.perf_counter around complete HTTP handler; token usage returned by provider (zero when model unavailable)",
    }
    (ROOT / "results" / "capstone-smoke-summary.json").write_text(
        json.dumps(summary, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    (ROOT / "results" / "capstone-smoke-extract.md").write_text(
        "# Unit 9 — actual structured log extract (10 valid + 1 rejected)\n\n"
        "Generated by `scripts/capstone_smoke.py::main` using `serve.py::ask` "
        "and `capstone_logging.py::instrument_http`. No model key was present.\n\n"
        "```json\n" + "\n".join(json.dumps(r, ensure_ascii=False) for r in records)
        + "\n```\n", encoding="utf-8"
    )
    print(json.dumps(summary, indent=2))
    print("Actual records:", LOG.relative_to(ROOT))
    print("Extract:", "results/capstone-smoke-extract.md")


if __name__ == "__main__":
    main()
